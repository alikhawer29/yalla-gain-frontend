const buildStatus = (enMap, arMap) => {
  const en = {};
  const ar = {};
  for (const [k, v] of Object.entries(enMap)) {
    en[k] = v;
    ar[k] = arMap[k] ?? (/^\d+$/.test(k) || /^\d{4}$/.test(k) ? v : v);
  }
  return { en, ar };
};

const { en: statusEn, ar: statusArMerged } = buildStatus(
  generated.status,
  statusAr
);

